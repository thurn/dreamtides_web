function printedId(state: BattleState, instance: InstanceId): CardId | null {
    const printing = state.instances[instance]?.printing;
    return printing?.kind === "card" || printing?.kind === "figmentCopy" ? printing.cardId : null;
}
/** Resolve metadata against the current first trigger match, independently of the worker. */
export function acceptedTutorialOverride(battle: TutorialBattleFoldState, engine: Engine, raw: unknown): PolicyOverrideSelection | null {
    if (typeof raw !== "object" || raw === null || Array.isArray(raw))
        return null;
    const state = battle.engine.slice.committed;
    const decision = engine.decision(state);
    if (decision === null)
        return null;
    const outcome = policyOverride(engine.view(state, decision.side), { kind: "topLevel", decision, legal: engine.legalActions(state, decision.side) }, battle.overrides);
    if (outcome?.kind !== "selected")
        return null;
    const fields = raw as Record<string, unknown>, selected = outcome.selection;
    return fields.id === selected.id && fields.triggerCardId === selected.triggerCardId && fields.actionCardId === selected.actionCardId && fields.instance === selected.instance ? selected : null;
}
/** Persist only frames generated by actual engine events; the engine slice is never patched. */
export function tutorialEngineTransition(state: FoldState, battle: TutorialBattleFoldState, engine: Engine, slice: BattleSlice, published: readonly EngineEvent[], seq: number, pendingOverride: PolicyOverrideSelection | null, cancelled: boolean): FoldState {
    const batch = batchStates(foldAdapterFor(engine), battle.engine.slice, slice, published);
    let next: TutorialBattleFoldState = { ...battle, engine: { ...battle.engine, slice }, pendingOverride: cancelled ? null : pendingOverride };
    const seen = [...state.tutorialTriggerIdsSeen];
    const checkpoints = [...battle.checkpoints];
    const enqueue = (presentation: TutorialBattlePresentation, before: BattleState, frame: BattleState): void => { checkpoints.push({ presentation, before, state: frame }); };
    const guidance = (event: TutorialTriggerEvent, source: TutorialGuidanceSource, before: BattleState, frame: BattleState, id: PresentationId, cardId?: CardId | import("../../types/identifiers").DreamwellCardId, text = "", kind?: "character" | "event", automatic = false): boolean => {
        const presentation = selectBattleGuidance(battle.init.tutorialTriggers, seen, event, source, id, cardId, text, kind, automatic);
        if (presentation === null)
            return false;
        seen.push(...presentation.messages.map(message => message.triggerId));
        enqueue(presentation, before, frame);
        return true;
    };
    let before = batch.before;
    for (const [index, event] of published.entries()) {
        const frame = batch.eventStates[index] ?? batch.state;
        const id = parsePresentationId(`${battle.init.battleId}:${String(seq)}:${String(index)}`);
        if (event.kind === "dreamwellDrawn") {
            next = { ...next, overrides: { ...next.overrides, dreamwell: { side: event.side, cardId: event.card, turnNumber: frame.turn.turnNumber } } };
            const definition = battle.init.dreamwellDeck.find(card => card.id === event.card);
            const source: TutorialGuidanceSource = { kind: "dreamwell", side: event.side, cardId: event.card };
            if (!guidance("dreamwell-resolve", source, before, frame, id, event.card, definition?.renderedText ?? ""))
                enqueue({ kind: "dreamwell-reveal", id, side: event.side, cardId: event.card, turnNumber: frame.turn.turnNumber }, before, frame);
        }
        else if (event.kind === "cardPlayed") {
            const cardId = printedId(frame, event.instance);
            const definition = battle.init.cardDefinitions.find(card => card.cardId === cardId);
            const cardKind = definition?.battleCardKind ?? "character";
            if (cardId !== null) {
                const source: TutorialGuidanceSource = { kind: "card", cardId, battleCardId: parseBattleCardId(event.instance), cardKind, side: event.side };
                if (!guidance("card-play", source, batch.before, frame, id, cardId, definition?.renderedText ?? "", cardKind, event.side === "enemy") && event.side === "enemy")
                    enqueue({ kind: "opponent-play", id, cardId, battleCardId: parseBattleCardId(event.instance), cardKind }, before, frame);
            }
        }
        else if (event.kind === "cardCreated" && event.printing.kind === "figment") {
            // A figment's card id is its authored catalog UUID; the engine printing retains it.
            const cardId = importFigmentCardId(event.printing.figment);
            if (cardId !== null)
                guidance("figment-created", { kind: "figment", cardId, battleCardId: parseBattleCardId(event.instance), side: event.side }, before, frame, id);
        }
        else if (event.kind === "phaseChanged" && event.active === "player" && (event.phase === "dusk" || event.phase === "night")) {
            guidance(event.phase === "dusk" ? "opponent-reposition-opportunity" : "player-night-phase", { kind: "battle", activeSide: event.active, turnNumber: frame.turn.turnNumber }, before, frame, id);
        }
        else if (event.kind === "laneResolved") {
            const active = before.turn.active;
            const dissolved = published.filter((edge): edge is Extract<EngineEvent, {
                kind: "dissolved";
            }> => edge.kind === "dissolved" && (edge.instance === event.challenger || edge.instance === event.blocker)).map(edge => ({ battleCardId: parseBattleCardId(edge.instance), side: edge.side }));
            const laneBefore = batch.eventStates.find(candidate => candidate?.sides[active].frontRank[event.lane] === event.challenger && (event.blocker === null || candidate.sides[active === "player" ? "enemy" : "player"].frontRank[event.lane] === event.blocker)) ?? batch.before;
            enqueue({ kind: "challenge-resolved", id, activeSide: active, slotId: `F${event.lane}`, challengerBattleCardId: parseBattleCardId(event.challenger), blockerBattleCardId: event.blocker === null ? null : parseBattleCardId(event.blocker), scored: event.scored === 0 ? null : { battleCardId: parseBattleCardId(event.challenger), side: active, points: event.scored }, dissolved }, laneBefore, frame);
            guidance("challenge-resolved", { kind: "challenge", activeSide: active, turnNumber: frame.turn.turnNumber, slotId: `F${event.lane}` }, frame, frame, parsePresentationId(`${id}:guidance`));
        }
        else if (event.kind === "blockersDesignated" && Object.keys(event.blockers).length > 0) {
            const blockers = Object.entries(event.blockers).map(([challenger, blocker]):import("./fold").OpponentBlockEntry => ({ battleCardId: parseBattleCardId(blocker), challengerBattleCardId: parseBattleCardId(challenger), slotId: `F${frame.sides[event.side].frontRank.indexOf(blocker)}` }));
            enqueue({ kind: "opponent-block", id, activeSide: event.side === "player" ? "enemy" : "player", blockers }, before, frame);
        }
        before = frame;
    }
    const selected = next.pendingOverride;
    const selectedSide = selected === null ? undefined : next.overrides.definitions.find(definition => definition.id === selected.id)?.trigger.side;
    if (selected !== null && selectedSide !== undefined && !battle.overrides.consumed.includes(selected.id) && published.some(event => event.kind === "cardPlayed" && event.side === selectedSide && event.instance === selected.instance) && slice.committed.turnLog.played[selectedSide].filter(play => play.instance === selected.instance).length > battle.engine.slice.committed.turnLog.played[selectedSide].filter(play => play.instance === selected.instance).length) {
        next = { ...next, pendingOverride: null, overrides: { ...next.overrides, consumed: [...next.overrides.consumed, selected.id] }, overrideCommits: [...next.overrideCommits, selected] };
    }
    next = { ...next, pendingOverride: slice.inFlight === null ? null : next.pendingOverride, ...tutorialCheckpointQueue(checkpoints) };
    return { ...state, battle: next, tutorialTriggerIdsSeen: seen };
}
import { lookupFigmentCatalogEntryById } from "../../battle/state/figment-catalog";
import { cardIdFromUnknown } from "../../types/card-identity";
function importFigmentCardId(figment: import("../../engine/state/ids").FigmentId): CardId | null {
    const id = cardIdFromUnknown(figment);
    return id === null ? null : lookupFigmentCatalogEntryById(id)?.id ?? id;
}
/** Advance an exact queue head while preserving its host's presentation domain. */
function completedCheckpoints<P extends TutorialBattlePresentation>(checkpoints: readonly TutorialCheckpoint<P>[], payload: Record<string, unknown>): readonly TutorialCheckpoint<P>[] | null {
    const first = checkpoints[0];
    if (first === undefined || payload.presentationId !== first.presentation.id) return null;
    const presentation = first.presentation;
    if (presentation.kind === "tutorial-guidance") {
        if (payload.messageIndex !== presentation.messageIndex) return null;
        if (presentation.messageIndex + 1 < presentation.messages.length)
            return [{ ...first, presentation: { ...presentation, messageIndex: presentation.messageIndex + 1 } }, ...checkpoints.slice(1)];
    }
    return checkpoints.slice(1);
}
export function completeTutorialCheckpoint(state: FoldState, payload: Record<string, unknown>): FoldState | null {
    const tutorial = tutorialBattleOf(state.battle);
    if (tutorial !== null) {
        const checkpoints = completedCheckpoints(tutorial.checkpoints, payload);
        return checkpoints === null ? null : { ...state, battle: { ...tutorial, ...tutorialCheckpointQueue(checkpoints) } };
    }
    const journey = journeyBattleOf(state.battle);
    if (journey?.guidance === undefined) return null;
    const checkpoints = completedCheckpoints(journey.guidance.checkpoints, payload);
    return checkpoints === null ? null : { ...state, battle: { ...journey, guidance: { ...journey.guidance, ...tutorialCheckpointQueue(checkpoints) } } };
}
/** A failed hand play is a presentation intent; its dry-run events never become gameplay. */
export function tutorialCardAttempt(state: FoldState, payload: Record<string, unknown>, ctx: import("../../eventlog/types").EventContext): FoldState | null {
    const battle = battleGuidanceOf(state.battle);
    const provider = getBattleInitProvider();
    const engine = provider?.engine ?? null;
    if (battle === null || engine === null || payload.battleId !== battle.init.battleId || currentTutorialPresentation(battle) !== null || battle.engine.slice.inFlight !== null || typeof payload.instance !== "string")
        return null;
    const board = battle.engine.slice.committed;
    const instance = board.sides.player.hand.find(id => id === payload.instance);
    if (instance === undefined || engine.decision(board)?.side !== "player" || engine.legalActions(board, "player").some(action => action.kind === "play" && action.card === instance))
        return null;
    let refusal = false;
    try {
        runStep(board, { kind: "play", card: instance, from: "hand" }, NO_PROMPTS, engine.catalog, { dryRun: true });
    }
    catch (error) {
        refusal = error instanceof EmptyPrompt && error.prompt.kind === "chooseTargets" && error.prompt.purpose.source === instance && error.prompt.purpose.role === "target" && error.prompt.side === "player" && error.prompt.min > 0 && error.prompt.candidates.length === 0;
    }
    const cardId = printedId(board, instance);
    if (!refusal || cardId === null)
        return null;
    const definition = state.battle?.mode.kind === "journey" ? createBattleCardDisplayResolver(battle.init.cardDefinitions).definition(cardId, board.instances[instance].variant) : battle.init.cardDefinitions.find(card => card.cardId === cardId);
    const cardKind = state.battle?.mode.kind === "journey" ? engine.view(board, "player").instances[instance]?.characteristics.cardType ?? engine.catalog.card(cardId).cardType : engine.catalog.card(cardId).cardType;
    const matches = matchTutorialGuidance(battle.init.tutorialTriggers, { event: "card-no-valid-targets", cardId, cardKind, renderedText: definition?.renderedText ?? (state.battle?.mode.kind === "journey" ? provider?.guidanceCardText?.(cardId) : undefined) ?? "", seenTriggerIds: new Set(state.tutorialTriggerIdsSeen) });
    if (matches.length === 0)
        return null;
    const presentation: import("./fold").TutorialGuidancePresentation = { kind: "tutorial-guidance", id: parsePresentationId(`${battle.init.battleId}:${ctx.seq}:refusal`), source: { kind: "card", cardId, battleCardId: parseBattleCardId(instance), cardKind, side: "player" }, messages: matches.map(trigger => ({ triggerId: trigger.id, speaker: trigger.speaker, text: trigger.text, duration: trigger.duration, ...(trigger.delay?.["card-no-valid-targets"] === undefined ? {} : { delay: trigger.delay["card-no-valid-targets"] }), horizontalOffset: trigger.horizontalOffset, verticalOffset: trigger.verticalOffset, bubbleWidth: trigger.bubbleWidth })), messageIndex: 0, automatic: false };
    const queue = tutorialCheckpointQueue([{ presentation, before: board, state: board }]);
    const tutorial = tutorialBattleOf(state.battle), journey = journeyBattleOf(state.battle);
    const nextBattle = tutorial !== null ? { ...tutorial, ...queue } : journey?.guidance === undefined ? null : { ...journey, guidance: { ...journey.guidance, ...queue } };
    return nextBattle === null ? null : { ...state, tutorialTriggerIdsSeen: [...state.tutorialTriggerIdsSeen, ...matches.map(match => match.id)], battle: nextBattle };
}
