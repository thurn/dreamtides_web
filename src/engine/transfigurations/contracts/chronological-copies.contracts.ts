import { describe, expect, it } from "vitest";
import { createCatalog, instanceCard, type EngineCardDefinition } from "../../catalog";
import { engineCardFromContent } from "../../content-catalog";
import { createEngine } from "../../engine";
import { createFoldAdapter, type BattleSlice } from "../../fold/slice";
import * as b from "../../dsl/builders";
import * as p from "../../effects/primitives";
import { triggered, onMaterialized, whenYouPlay, triggeringCard } from "../../dsl/triggers";
import type { Variant } from "../../dsl/types";
import { ScriptedSource, NO_PROMPTS } from "../../steps/sources";
import { runStep } from "../../steps/runner";
import { boardState } from "../../testing/board";
import { syntheticId } from "../../testing/synthetic-cards";
import { stateHash, serializeState } from "../../state/hash";
import { FORM_FILLER, FORM_EVENT, formContent } from "./transfigurations-01.fixtures";

const twice: Variant = { amplified: false, transfigurationApplications: [{ form: "Inspired" }, { form: "Inspired" }] };
const deck = Array.from({ length: 12 }, () => FORM_FILLER.id);
const slice = (committed: BattleSlice["committed"]): BattleSlice => ({ committed, inFlight: null, publishedEvents: 0, attempt: 0 });

for (const side of ["player", "enemy"] as const) describe(`${side} chronological retained values`, () => {
  it("retains complete history in an actual hand copy and independent same-UUID neighbor", () => {
    const card = engineCardFromContent(formContent({ abilities: () => [b.event(p.createCopyInHand(b.self()))] }));
    const catalog = createCatalog([card, FORM_FILLER], []), engine = createEngine(catalog);
    const { state, ids } = boardState(catalog, { active: side, phase: "day", [side]: { hand: [{ cardId: card.id, ...twice }, card.id], deck, energy: 20 } });
    const done = engine.apply(state, side, { kind: "play", card: ids[side].hand[0], from: "hand" }, NO_PROMPTS);
    const made = done.events.find(e => e.kind === "cardCopied");
    expect(made).toBeDefined(); if (made?.kind !== "cardCopied") throw new Error("Missing hand copy");
    expect(done.state.instances[made.copy].variant).toEqual(twice);
    expect(done.state.instances[ids[side].hand[1]].variant).toEqual({ amplified: false });
    expect(done.events.filter(e => e.kind === "cardDrawn" && e.side === side)).toHaveLength(2);
    const replayed = engine.apply(done.state, side, { kind: "play", card: made.copy, from: "hand" }, NO_PROMPTS);
    expect(replayed.events.filter(e => e.kind === "cardDrawn" && e.side === side)).toHaveLength(2);
  });
  it("makes a real stack copy whose two appends execute once each", () => {
    const card = engineCardFromContent(formContent()), echo: EngineCardDefinition = { ...FORM_FILLER, id: syntheticId(0x7540), status: "authored", abilities: () => [triggered(whenYouPlay({ cardType: "event" }), p.copyCard(triggeringCard()))] };
    const catalog = createCatalog([card, echo, FORM_FILLER], []), engine = createEngine(catalog);
    const { state, ids } = boardState(catalog, { active: side, phase: "day", [side]: { hand: [{ cardId: card.id, ...twice }], back: [echo.id], deck, energy: 20 } });
    const started = runStep(state, { kind: "play", card: ids[side].hand[0], from: "hand" }, NO_PROMPTS, catalog);
    if (started.kind !== "done") throw new Error("Unexpected prompt");
    const copied = runStep(started.state, { kind: "resolveTrigger" }, NO_PROMPTS, catalog);
    if (copied.kind !== "done") throw new Error("Unexpected copy prompt");
    const event = copied.events.find(e => e.kind === "cardCopied");
    if (event?.kind !== "cardCopied") throw new Error("Missing stack copy");
    expect(copied.state.instances[event.copy].variant).toEqual(twice);
    const first = runStep(copied.state, { kind: "resolveTop" }, NO_PROMPTS, catalog);
    if (first.kind !== "done") throw new Error("Unexpected resolution prompt");
    expect(first.events.filter(e => e.kind === "cardDrawn" && e.side === side)).toHaveLength(2);
    const second = runStep(first.state, { kind: "resolveTop" }, NO_PROMPTS, catalog);
    if (second.kind !== "done") throw new Error("Unexpected original prompt");
    expect(second.events.filter(e => e.kind === "cardDrawn" && e.side === side)).toHaveLength(2);
    expect(second.state.sides[side].score).toBe(2);
    expect(engine.view(second.state, side).instances[event.copy]).toBeUndefined();
  });
  it("retains numeric history in an actual zero-spark figment copy", () => {
    const card = engineCardFromContent(formContent({ cardType: "Character", spark: 3, renderedText: "0●: Materialize a figment copy.", abilities: () => [b.activated([b.energy(0)], p.materializeFigmentCopy(b.self(), { zeroSpark: true }))] }));
    const variant: Variant = { amplified: false, transfigurationApplications: [{ form: "Kindled" }, { form: "Kindled" }] };
    const catalog = createCatalog([card, FORM_FILLER], []), engine = createEngine(catalog);
    const { state, ids } = boardState(catalog, { active: side, phase: "day", [side]: { hand: [{ cardId: card.id, ...variant }], energy: 20 } });
    const played = engine.apply(state, side, { kind: "play", card: ids[side].hand[0], from: "hand" }, NO_PROMPTS);
    const done = engine.apply(played.state, side, { kind: "activate", source: ids[side].hand[0], ability: 0 }, NO_PROMPTS);
    const copy = Object.values(done.state.instances).find(value => value.printing.kind === "figmentCopy");
    expect(copy).toBeDefined();
    expect(copy!.variant).toEqual(variant);
    expect(instanceCard(catalog, copy!).spark).toBe(0);
    expect(instanceCard(catalog, done.state.instances[ids[side].hand[0]]).spark).toBe(12);
  });
  it("preserves a gained ordered source after the source and recipient leave play", () => {
    const card = engineCardFromContent(formContent({ cardType: "Character", spark: 2, renderedText: "▸Materialized: Gain 2⍟.", abilities: () => [triggered(onMaterialized(), p.gainPoints(2))] }));
    const learner: EngineCardDefinition = { ...FORM_FILLER, id: syntheticId(0x7541), status: "authored", abilities: () => [b.activated([b.discardCost(1)], p.gainAbilities(p.banishCards([b.everyIn("void")]))) ] };
    const dissolve: EngineCardDefinition = { ...FORM_EVENT, id: syntheticId(0x7542), abilities: () => [b.event(p.dissolve(b.target(b.characterYouControl())))] };
    const variant: Variant = { amplified: false, transfigurationApplications: [{ form: "Kindled" }, { form: "Resonant" }] };
    const catalog = createCatalog([card, learner, dissolve], []), engine = createEngine(catalog);
    const { state, ids } = boardState(catalog, { active: side, phase: "day", [side]: { back: [learner.id], hand: [{ cardId: card.id, ...variant }, dissolve.id], energy: 20 } });
    const learned = engine.apply(state, side, { kind: "activate", source: ids[side].back[0]!, ability: 0 }, new ScriptedSource([[ids[side].hand[0]]]));
    expect(learned.state.instances[ids[side].back[0]!].status.gainedAbilities).toEqual([{ cardId: card.id, variant }]);
    const ended = engine.apply(learned.state, side, { kind: "play", card: ids[side].hand[1], from: "hand" }, new ScriptedSource([[ids[side].back[0]!]]));
    expect(ended.state.sides[side].score).toBe(2);
    expect(ended.state.instances[ids[side].hand[0]].zone).toBe("banished");
    expect(ended.state.instances[ids[side].back[0]!].zone).toBe("void");
  });
  it("reloads a real optional prompt and settles an accepted answer exactly once", () => {
    const card = engineCardFromContent(formContent({ abilities: () => [b.event(p.optional(p.gainPoints(2)))] }));
    const catalog = createCatalog([card, FORM_FILLER], []), adapter = createFoldAdapter(createEngine(catalog));
    const { state, ids } = boardState(catalog, { active: side, phase: "day", [side]: { hand: [{ cardId: card.id, ...twice }], deck, energy: 20 } });
    const opened = adapter.reduce(slice(state), { kind: "battleAction", side, action: { kind: "play", card: ids[side].hand[0], from: "hand" } });
    if (opened.kind !== "applied") throw new Error("Play bounced");
    const loaded = JSON.parse(JSON.stringify(opened.slice)) as BattleSlice, prompt = adapter.pending(loaded)!.prompt;
    expect(adapter.pending(opened.slice)?.prompt).toEqual(prompt);
    const answer = { kind: "answer" as const, side, promptId: prompt.id, value: true };
    const foreign = adapter.reduce(loaded, { ...answer, side: side === "player" ? "enemy" : "player" });
    expect(foreign.kind).toBe("bounced");
    const main = adapter.reduce(opened.slice, answer), restored = adapter.reduce(loaded, answer);
    if (main.kind !== "applied" || restored.kind !== "applied") throw new Error("Answer bounced");
    expect(stateHash(main.slice.committed)).toBe(stateHash(restored.slice.committed));
    expect(restored.slice.committed.sides[side].score).toBe(2);
    expect(restored.published.filter(e => e.kind === "cardDrawn" && e.side === side)).toHaveLength(2);
    expect(adapter.reduce(restored.slice, answer).kind).toBe("bounced");
  });
  it("keeps the prior committed payment while a failed resolution publishes no appended draws", () => {
    const card = { ...engineCardFromContent(formContent()), synthetic: { resolve() { throw new Error("synthetic chronological failure"); } } };
    const catalog = createCatalog([card, FORM_FILLER], []), adapter = createFoldAdapter(createEngine(catalog));
    const { state, ids } = boardState(catalog, { active: side, phase: "day", [side]: { hand: [{ cardId: card.id, ...twice }], deck, energy: 20 } });
    const before = serializeState(state), done = adapter.reduce(slice(state), { kind: "battleAction", side, action: { kind: "play", card: ids[side].hand[0], from: "hand" } });
    if (done.kind !== "applied") throw new Error("Play bounced");
    expect(done.error).not.toBeNull();
    expect(serializeState(state)).toBe(before);
    expect(done.slice.committed.sides[side].currentEnergy).toBe(17);
    expect(done.slice.committed.sides[side].deck).toHaveLength(12);
    expect(done.published.some(e => e.kind === "cardDrawn")).toBe(false);
  });
  it("preserves independent C12 paired references after chronological appends", () => {
    const moved = p.banishCards([b.fromVoid({ subtype: "Warrior" })]);
    const card = engineCardFromContent(formContent({ abilities: () => [b.event(p.sequence(moved, p.gainPoints(b.costOf(b.cardsMovedBy(moved)))))] }));
    const mage: EngineCardDefinition = { ...FORM_FILLER, id: syntheticId(0x7543), subtype: "Mage", costs: [b.energy(2)] };
    const catalog = createCatalog([card, mage, FORM_FILLER], []), engine = createEngine(catalog);
    const { state, ids } = boardState(catalog, { active: side, phase: "day", [side]: { hand: [{ cardId: card.id, ...twice, typeRemap: "Mage" }], void: [mage.id, FORM_FILLER.id], deck, energy: 20 } });
    const done = engine.apply(state, side, { kind: "play", card: ids[side].hand[0], from: "hand" }, new ScriptedSource([[ids[side].void[0]]]));
    expect(done.state.sides[side].score).toBe(2);
    expect(done.state.instances[ids[side].void[1]].zone).toBe("void");
    expect(done.events.filter(e => e.kind === "cardDrawn" && e.side === side)).toHaveLength(2);
  });
});
