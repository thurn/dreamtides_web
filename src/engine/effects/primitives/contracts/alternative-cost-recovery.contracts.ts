/** Saved continuations, privacy and payment atomicity for the new route. */
import { describe, expect, it } from "vitest";
import { energy, event, giveOpponentPointsCost, keyword } from "../../../dsl/builders";
import type { EngineEvent } from "../../../events";
import { createEngine } from "../../../engine";
import { createFoldAdapter, type BattleSlice } from "../../../fold/slice";
import type { EngineLogRecord } from "../../../log";
import { promptFingerprint } from "../../../prompts/fingerprint";
import { isLegalAnswer } from "../../../prompts/answers";
import { isWellFormedPrompt } from "../../../prompts/structure";
import { stateHash } from "../../../state/hash";
import { SIDES, opponent } from "../../../state/ids";
import { NO_PROMPTS } from "../../../steps/sources";
import { runStep } from "../../../steps/runner";
import { planCosts, payCosts } from "../../../rules/costs";
import { greedyAnswer } from "../../../policy/prompts";
import { revealToBoth } from "../../../view/knowledge";
import { promptView } from "../../../view/view";
import { gainPoints } from "../gain-points";
import { alternativeApplied, alternativeCard, alternativeFixture, alternativeSlice, legalAlternativeMode } from "./alternative-cost-support";

const restored = (slice: BattleSlice): BattleSlice => JSON.parse(JSON.stringify(slice)) as BattleSlice;
describe.each(SIDES)("alternativeCost recovery for %s", side => {
  const other = opponent(side);
  it("reloads both route and target decisions, rejects invalid concurrent input, cancels and commits once", () => {
    const f = alternativeFixture(side);
    const records: EngineLogRecord[] = [];
    const fold = createFoldAdapter(f.engine, { checkEventPrefix: true, log: record => records.push(record) });
    const opened = alternativeApplied(fold.reduce(alternativeSlice(f.state), { kind: "battleAction", side, action: f.action })).slice;
    const route = fold.pending(opened)!;
    expect(route.prompt.kind).toBe("chooseMode");
    expect(stateHash(opened.committed)).toBe(stateHash(f.state));
    const cold = createFoldAdapter(createEngine(f.engine.catalog), { checkEventPrefix: true });
    expect(cold.pending(restored(opened))).toEqual(route);
    expect(cold.reduce(opened, { kind: "answer", side: other, promptId: route.prompt.id, value: 1 })).toEqual({ kind: "bounced", reason: "notYourPrompt" });
    expect(cold.reduce(opened, { kind: "answer", side, promptId: route.prompt.id, value: 99 })).toEqual({ kind: "bounced", reason: "illegalAnswer" });
    expect(cold.reduce(opened, { kind: "battleAction", side, action: f.action })).toEqual({ kind: "bounced", reason: "stepInFlight" });
    const selected = alternativeApplied(cold.reduce(restored(opened), { kind: "answer", side, promptId: route.prompt.id, value: 1 })).slice;
    const target = cold.pending(selected)!;
    expect(target.prompt.kind).toBe("chooseTargets");
    expect(stateHash(selected.committed)).toBe(stateHash(f.state));
    expect(createFoldAdapter(createEngine(f.engine.catalog)).pending(restored(selected))).toEqual(target);
    const cancelled = alternativeApplied(cold.reduce(restored(selected), { kind: "cancel", side, promptId: target.prompt.id })).slice;
    expect(stateHash(cancelled.committed)).toBe(stateHash(f.state));
    const reopened = alternativeApplied(fold.reduce(cancelled, { kind: "battleAction", side, action: f.action })).slice;
    expect(fold.reduce(reopened, { kind: "answer", side, promptId: route.prompt.id, value: 1 })).toEqual({ kind: "bounced", reason: "stalePrompt" });
    const newRoute = fold.pending(reopened)!;
    const targeted = alternativeApplied(fold.reduce(reopened, { kind: "answer", side, promptId: newRoute.prompt.id, value: 1 })).slice;
    const newTarget = fold.pending(targeted)!;
    const paid = alternativeApplied(fold.reduce(targeted, { kind: "answer", side, promptId: newTarget.prompt.id, value: [f.ids[other].back[1]!] })).slice;
    expect(paid.inFlight).toBeNull();
    expect(paid.committed.sides[other].score).toBe(5);
    expect(paid.committed.sides[side].score).toBe(0);
    expect(paid.committed.sides[side].currentEnergy).toBe(10);
    expect(paid.committed.turnLog.played[side]).toHaveLength(1);
    expect(fold.reduce(paid, { kind: "answer", side, promptId: newTarget.prompt.id, value: [f.ids[other].back[1]!] })).toEqual({ kind: "bounced", reason: "noPendingPrompt" });
    expect(records.some(record => record.event === "engine.promptOpened" && record.cardId === alternativeCard(1).id)).toBe(true);
    expect(records.filter(record => record.event === "engine.action")).toHaveLength(1);
  });
  it("keeps exact route metadata in the actor/public view and fingerprints it, concealing hidden and private payments", () => {
    const f = alternativeFixture(side);
    const fold = createFoldAdapter(f.engine);
    const opened = alternativeApplied(fold.reduce(alternativeSlice(f.state), { kind: "battleAction", side, action: f.action })).slice;
    const pending = fold.pending(opened)!;
    const prompt = pending.prompt;
    if (prompt.kind !== "chooseMode") throw new Error("Expected route choice");
    expect(isWellFormedPrompt(prompt)).toBe(true);
    expect(prompt.options).toEqual([{ mode: 0, route: "normal", legal: true }, { mode: 1, route: "alternativeCost", costs: [energy(0), giveOpponentPointsCost(5)], legal: true }]);
    expect(legalAlternativeMode(prompt, 0)).toBe(true);
    expect(legalAlternativeMode(prompt, 1)).toBe(true);
    expect(isWellFormedPrompt({ ...prompt, options: prompt.options.map(({ costs: _costs, ...option }) => option) })).toBe(false);
    const fingerprint = promptFingerprint(prompt);
    expect(promptFingerprint({ ...prompt, options: prompt.options.map(option => option.route === "alternativeCost" ? { ...option, costs: [energy(0), giveOpponentPointsCost(6)] } : option) })).not.toBe(fingerprint);
    const input = JSON.stringify(prompt), before = stateHash(pending.display);
    expect(promptView(prompt, side, pending.display)).toEqual(prompt);
    const hidden = promptView(prompt, other, pending.display);
    expect(hidden.purpose.source).toBeNull();
    if (hidden.kind !== "chooseMode") throw new Error("Wrong projection");
    expect(hidden.options).toEqual([{ mode: 0, legal: true }, { mode: 1, legal: true }]);
    const known = restored({ ...opened, committed: pending.display }).committed;
    revealToBoth(known, [f.id]);
    expect(promptView(prompt, other, known)).toEqual(prompt);
    const privateView = promptView({ ...prompt, privateTo: side }, other, known);
    if (privateView.kind !== "chooseMode") throw new Error("Wrong private projection");
    expect(privateView.options[1].costs).toBeUndefined();
    expect(privateView.options[1].route).toBe("alternativeCost");
    expect(stateHash(pending.display)).toBe(before);
    expect(JSON.stringify(prompt)).toBe(input);
    expect(isLegalAnswer(prompt, greedyAnswer(prompt, () => null, () => new Set(), 0))).toBe(true);
    expect(greedyAnswer({ ...prompt, options: prompt.options.map(option => ({ ...option, legal: option.mode === 1 })) }, () => null, () => new Set(), 0)).toBe(1);
    // Metadata-free ordinary Offering keeps its original shape and fingerprint on reload.
    const legacy = alternativeFixture(side, alternativeCard(20, [keyword("offering"), event(gainPoints(0))]), { hand: [alternativeCard(20).id, alternativeCard(20).id] });
    const oldFold = createFoldAdapter(legacy.engine);
    const oldOpen = alternativeApplied(oldFold.reduce(alternativeSlice(legacy.state), { kind: "battleAction", side, action: legacy.action })).slice;
    const oldPrompt = oldFold.pending(oldOpen)!.prompt;
    if (oldPrompt.kind !== "chooseMode") throw new Error("Expected legacy Offering choice");
    expect(oldPrompt.options).toEqual([{ mode: 0, legal: true }, { mode: 1, legal: true }]);
    expect(promptFingerprint(createFoldAdapter(createEngine(legacy.engine.catalog)).pending(restored(oldOpen))!.prompt)).toBe(promptFingerprint(oldPrompt));
  });
  it("rolls back real energy and grant payments when a synthetic transaction fails after payment", () => {
    const costs = [energy(1), giveOpponentPointsCost(5)];
    const card = alternativeCard(21, [], { synthetic: { play(ctx, source) {
      const plan = planCosts(ctx, side, source, costs, null, role => ({ source, cardId: alternativeCard(21).id, ability: 0, role }), [source]);
      ctx.commitPoint();
      payCosts(ctx, side, source, plan);
      throw new Error("synthetic postpayment failure");
    } } });
    const f = alternativeFixture(side, card);
    const before = stateHash(f.state), observed: EngineEvent[] = [];
    expect(() => runStep(f.state, { kind: "play", card: f.id, from: "hand" }, NO_PROMPTS, f.engine.catalog, { observeEvent: event => observed.push(event) })).toThrow(/postpayment failure/);
    expect(observed.filter(event => event.kind === "pointsScored")).toEqual([{ kind: "pointsScored", side: other, amount: 5, cause: "effect" }]);
    expect(observed.findIndex(event => event.kind === "energyChanged")).toBeLessThan(observed.findIndex(event => event.kind === "pointsScored"));
    expect(stateHash(f.state)).toBe(before);
    expect(f.state.sides[side].currentEnergy).toBe(10);
    expect(f.state.sides[other].score).toBe(0);
    expect(f.state.instances[f.id].zone).toBe("hand");
    expect(f.state.turnLog.played[side]).toEqual([]);
  });
});
