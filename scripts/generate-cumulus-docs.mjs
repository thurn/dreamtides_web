function tokenGroupFor(name) {
  for (const group of TOKEN_GROUPS) {
    for (const prefix of group.prefixes) {
      // A bare family name matches itself and any hyphenated descendant
      // ("accent" covers --accent and --accent-strong); a prefix written with
      // a trailing hyphen matches descendants only ("radius-" covers
      // --radius-panel but not a bare --radius).
      const family = prefix.replace(/-$/, "");
      if (name === prefix || name.startsWith(`${family}-`)) {
        return group.title;
      }
    }
  }
  return "Other";
}

/**
 * PURE core: render the public token reference (tokens.md) from the deduped CSS
 * token list and the trailing-comment notes. Tokens are grouped per
 * TOKEN_GROUPS, preserving source order within each group.
 */
export function renderTokensMarkdown(tokens, notes) {
  const byGroup = new Map();
  for (const token of tokens) {
    const title = tokenGroupFor(token.name);
    if (!byGroup.has(title)) byGroup.set(title, []);
    byGroup.get(title).push(token);
  }

  const lines = [];
  lines.push(`<!-- GENERATED by scripts/generate-cumulus-docs.mjs — do not edit by hand.
     Source: src/cumulus/primitives/cumulus-tokens.css.
     Regenerate: npm run cumulus-docs -->`);
  lines.push("");
  lines.push("# Cumulus design tokens");
  lines.push("");
  lines.push(
    'Every visual value in UI code — spacing, color, type, radius, shadow, motion — comes from this vocabulary. In Cumulus TS/TSX reference a token with `token("--name")` (`src/cumulus/primitives/tokens.ts`, typed; returns the `var(--name)` string); in CSS write `var(--name)`. Tokens apply within the `.cumulus` subtree. Pick tokens by *role*, not by value; when no role fits, raise a token-system change instead of writing a literal. Policy: SKILL.md, "Tokens" section.',
  );

  const orderedTitles = [
    ...TOKEN_GROUPS.map((g) => g.title),
    ...(byGroup.has("Other") ? ["Other"] : []),
  ];
  for (const title of orderedTitles) {
    const groupTokens = byGroup.get(title);
    if (!groupTokens || groupTokens.length === 0) continue;
    const groupNote = TOKEN_GROUPS.find((g) => g.title === title)?.note;
    lines.push("");
    lines.push(`## ${title}`);
    lines.push("");
    if (groupNote) {
      lines.push(groupNote);
      lines.push("");
    }
    lines.push("| Token | Value | Notes |");
    lines.push("| --- | --- | --- |");
    for (const token of groupTokens) {
      const note = notes.get(token.name) ?? "";
      lines.push(
        `| ${codeSpan(`--${token.name}`)} | ${codeSpan(tableCell(token.value))} | ${tableCell(note)} |`,
      );
    }
  }
  lines.push("");
  return lines.join("\n");
}

/**
 * Every file `npm run cumulus-docs` would write, as an absolute-path → content
 * map, computed from the live sources without touching disk. `main()` writes
 * this map (and sweeps stale component .md files not in it); the drift
 * contract test compares it against the committed files, so "edited a demo or
 * component but forgot to regenerate" fails the build. Note the SKILL.md
 * entry is the CURRENT file with the generated index re-spliced — hand-edited
 * prose passes through unchanged.
 */
export function computeDocOutputs() {
  const registryEntries = extractRegistryOrder(
    readFileSync(REGISTRY_PATH, "utf8"),
    relative(ROOT, REGISTRY_PATH),
  );
  const metadata = JSON.parse(readFileSync(METADATA_PATH, "utf8"));
  const countByTitle = new Map(
    computeConsumerCounts().map((c) => [c.title, c.count]),
  );

  const docs = [];
  for (const entry of registryEntries) {
    // Import specifiers are relative to the registry file, without extension.
    const demoPath = `${resolve(dirname(REGISTRY_PATH), entry.modulePath)}.tsx`;
    const doc = extractDemoDoc(
      readFileSync(demoPath, "utf8"),
      relative(ROOT, demoPath),
      entry.exportName,
    );
    if (!(doc.docName in metadata)) {
      throw new Error(
        `${relative(ROOT, demoPath)}: docName "${doc.docName}" has no entry in ${relative(ROOT, METADATA_PATH)} — run npm run cumulus-metadata first`,
      );
    }
    docs.push(doc);
  }

  const ids = new Set(docs.map((doc) => doc.id));
  if (ids.size !== docs.length) {
    throw new Error("duplicate component ids in the registry");
  }

  const files = new Map();
  for (const doc of docs) {
    files.set(
      join(COMPONENTS_OUT_DIR, `${doc.id}.md`),
      renderComponentMarkdown(
        doc,
        metadata[doc.docName],
        countByTitle.get(doc.title),
      ),
    );
  }

  const skillText = readFileSync(SKILL_PATH, "utf8");
  files.set(
    SKILL_PATH,
    spliceGeneratedIndex(skillText, renderIndexSection(docs, countByTitle)),
  );

  const cssText = readFileSync(TOKENS_CSS_PATH, "utf8");
  const dedupedTokens = [...dedupeLastWins(parseCssTokens(cssText))].map(
    ([name, entry]) => ({ name, value: entry.value }),
  );
  files.set(
    TOKENS_OUT_PATH,
    renderTokensMarkdown(dedupedTokens, extractTokenNotes(cssText)),
  );

  return { files, docs, dedupedTokens };
}

/** Output locations, for the drift contract test. */
export const DOC_OUTPUT_PATHS = {
  componentsDir: COMPONENTS_OUT_DIR,
  skillPath: SKILL_PATH,
  tokensPath: TOKENS_OUT_PATH,
};

function main() {
  const { files, docs, dedupedTokens } = computeDocOutputs();

  // Write one reference file per component, then sweep stale ones: any .md in
  // the output directory this run did not produce belongs to a renamed or
  // unregistered component and must not survive as authoritative-looking docs.
  mkdirSync(COMPONENTS_OUT_DIR, { recursive: true });
  for (const [path, content] of files) {
    writeFileSync(path, content);
  }
  let sweptCount = 0;
  for (const existing of readdirSync(COMPONENTS_OUT_DIR)) {
    const full = join(COMPONENTS_OUT_DIR, existing);
    if (existing.endsWith(".md") && !files.has(full)) {
      unlinkSync(full);
      sweptCount += 1;
    }
  }

  console.log(
    `Wrote ${docs.length} component reference${docs.length === 1 ? "" : "s"} to ${relative(ROOT, COMPONENTS_OUT_DIR)}${sweptCount > 0 ? ` (swept ${sweptCount} stale)` : ""}`,
  );
  console.log(`Updated component index in ${relative(ROOT, SKILL_PATH)}`);
  console.log(
    `Wrote ${dedupedTokens.length} design tokens to ${relative(ROOT, TOKENS_OUT_PATH)}`,
  );
}

const invokedPath = process.argv[1] ? resolve(process.argv[1]) : "";
if (invokedPath === fileURLToPath(import.meta.url)) main();
