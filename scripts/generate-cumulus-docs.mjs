/**
 * PURE core: render one component's markdown reference from its demo doc and
 * docgen PropMeta[] (the cumulus-metadata.json entry under doc.docName).
 */
export function renderComponentMarkdown(doc, props, consumerCount) {
  const lines = [];
  lines.push(GENERATED_HEADER(doc.id));
  lines.push("");
  lines.push(`# ${doc.title}`);
  lines.push("");
  lines.push(
    `${doc.group} · Live demo & interactive props: \`/cumulus#/${doc.id}\``,
  );
  if (typeof consumerCount === "number") {
    lines.push("");
    lines.push(
      `Source-module importers: **${consumerCount}** (value imports outside docs and test/type fixtures; not a production-liveness measure).`,
    );
  }
  lines.push("");
  lines.push(doc.blurb);
  if (doc.callout) {
    lines.push("");
    lines.push(`> **Guidance:** ${doc.callout}`);
  }
  for (const paragraph of doc.details ?? []) {
    lines.push("");
    lines.push(paragraph);
  }

  lines.push("");
  lines.push("## Props");
  lines.push("");
  if (doc.propsNote) {
    lines.push(doc.propsNote);
    lines.push("");
  }
  if (!props || props.length === 0) {
    lines.push("This component takes no props.");
  } else {
    lines.push("| Prop | Type | Required | Default | Description |");
    lines.push("| --- | --- | --- | --- | --- |");
    for (const prop of props) {
      lines.push(
        `| ${codeSpan(prop.name)} | ${typeCell(prop)} | ${prop.required ? "yes" : "no"} | ${prop.defaultValue !== null && prop.defaultValue !== undefined ? codeSpan(tableCell(prop.defaultValue)) : "—"} | ${tableCell(prop.description)} |`,
      );
    }
    for (const prop of props) {
      if (!prop.nested) continue;
      const fields = prop.nested.fields ?? [];
      const variants = prop.nested.variants ?? [];
      if (fields.length === 0 && variants.length === 0) continue;
      lines.push("");
      lines.push(
        `### ${codeSpan(prop.name)}: the ${codeSpan(prop.nested.name)} model`,
      );

      function appendFieldTable(modelFields) {
        lines.push("");
        lines.push("| Field | Type | Optional | Description |");
        lines.push("| --- | --- | --- | --- |");
        for (const field of modelFields) {
          lines.push(
            `| ${codeSpan(field.name)} | ${codeSpan(tableCell(field.tsType))} | ${field.optional ? "yes" : "no"} | ${tableCell(field.description)} |`,
          );
        }
      }

      if (fields.length > 0) appendFieldTable(fields);
      for (const variant of variants) {
        lines.push("");
        lines.push(`#### ${codeSpan(variant.name)}`);
        appendFieldTable(variant.fields);
      }
    }
  }

  if (doc.usage.length > 0) {
    lines.push("");
    lines.push("## Usage");
    for (const [index, snippet] of doc.usage.entries()) {
      lines.push("");
      if (snippet.label) {
        lines.push(`### ${snippet.label}`);
        lines.push("");
      } else if (doc.usage.length > 1) {
        lines.push(`### Variant ${index + 1}`);
        lines.push("");
      }
      if (snippet.note) {
        lines.push(snippet.note);
        lines.push("");
      }
      lines.push("```tsx");
      lines.push(snippet.code);
      lines.push("```");
    }
  }

  lines.push("");
  return lines.join("\n");
}

/**
 * PURE core: render the component index table (registry order, grouped by
 * first appearance of each group) that gets spliced into SKILL.md.
 */
export function renderIndexSection(docs, countByTitle) {
  const lines = [];
  lines.push("| Component | Group | Consumers | Reference | What it is |");
  lines.push("| --- | --- | --- | --- | --- |");
  for (const doc of docs) {
    const count = countByTitle?.get(doc.title);
    const consumers = count === undefined ? "—" : count;
    lines.push(
      `| ${doc.title} | ${doc.group} | ${consumers} | [components/${doc.id}.md](components/${doc.id}.md) | ${tableCell(firstSentence(doc.blurb))} |`,
    );
  }
  return lines.join("\n");
}

/**
 * PURE core: replace the generated index section of SKILL.md (the text between
 * the BEGIN/END markers) with freshly rendered content. Throws when a marker
 * is missing so a hand-edit that drops one fails loudly instead of silently
 * skipping the update.
 */
export function spliceGeneratedIndex(skillText, indexMarkdown) {
  const begin = skillText.indexOf(INDEX_BEGIN_MARKER);
  const end = skillText.indexOf(INDEX_END_MARKER);
  if (begin === -1 || end === -1 || end < begin) {
    throw new Error(
      `SKILL.md is missing the generated-index markers (${INDEX_BEGIN_MARKER} / ${INDEX_END_MARKER})`,
    );
  }
  const before = skillText.slice(0, begin + INDEX_BEGIN_MARKER.length);
  const after = skillText.slice(end);
  return `${before}\n${indexMarkdown}\n${after}`;
}

/**
 * PURE core: collect the trailing same-line documentation comments from the
 * tokens CSS — `--name: value;  /* prose *\/` — keyed by token name.
 * parseCssTokens strips ordinary comments (it only preserves `@kind` markers),
 * so this line-based pass recovers the human notes that make the token list
 * self-explanatory. `@kind` markers are display-grouping metadata, not prose,
 * and are skipped. A name declared more than once keeps the last note seen,
 * matching the cascade's last-wins value resolution.
 */
export function extractTokenNotes(cssText) {
  const notes = new Map();
  const lineRe =
    /^\s*--([a-zA-Z0-9_-]+)\s*:[^;]*;[ \t]*\/\*\s*(.+?)\s*\*\/\s*$/;
  for (const line of cssText.split("\n")) {
    const match = line.match(lineRe);
    if (!match) continue;
    const [, name, note] = match;
    if (note.startsWith("@kind")) continue;
    notes.set(name, note);
  }
  return notes;
}

