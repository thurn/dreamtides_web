/** Parse a source text into a TS AST without touching the filesystem. */
function parseSource(sourceText, fileName) {
  return ts.createSourceFile(
    fileName,
    sourceText,
    ts.ScriptTarget.Latest,
    /* setParentNodes */ true,
    fileName.endsWith(".tsx") ? ts.ScriptKind.TSX : ts.ScriptKind.TS,
  );
}

/**
 * Extract the literal string value of an AST node, or throw. Accepts a plain
 * string literal and a substitution-free template literal — the two forms the
 * demo files use for doc prose. Anything else (a template with `${...}`, an
 * identifier, a concatenation) is rejected so doc fields stay statically
 * extractable.
 */
function literalString(node, context) {
  if (ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node)) {
    return node.text;
  }
  if (ts.isTemplateExpression(node)) {
    throw new Error(
      `${context}: template literal uses \${...} substitution; doc fields must be plain literals so the cumulus-docs generator can extract them statically`,
    );
  }
  throw new Error(
    `${context}: expected a string literal (got ${ts.SyntaxKind[node.kind]})`,
  );
}

/** Find an object literal's property initializer by name, or undefined. */
function propertyInitializer(objectLiteral, name) {
  for (const prop of objectLiteral.properties) {
    if (
      ts.isPropertyAssignment(prop) &&
      ts.isIdentifier(prop.name) &&
      prop.name.text === name
    ) {
      return prop.initializer;
    }
  }
  return undefined;
}

/**
 * PURE core: parse registry.ts source text into the ordered component list —
 * `[{ exportName, modulePath }]` in CUMULUS_COMPONENTS order, where modulePath
 * is the import specifier (e.g. "./demos/pressable"). Order is the canonical
 * catalog order the doc site's table of contents renders.
 */
export function extractRegistryOrder(sourceText, fileName = "registry.ts") {
  const source = parseSource(sourceText, fileName);

  // Map each imported identifier to its module specifier.
  const importByName = new Map();
  for (const statement of source.statements) {
    if (!ts.isImportDeclaration(statement)) continue;
    const clause = statement.importClause;
    if (!clause?.namedBindings || !ts.isNamedImports(clause.namedBindings)) {
      continue;
    }
    const specifier = statement.moduleSpecifier;
    if (!ts.isStringLiteral(specifier)) continue;
    for (const element of clause.namedBindings.elements) {
      importByName.set(element.name.text, specifier.text);
    }
  }

  // Find the CUMULUS_COMPONENTS array literal and read its identifiers in order.
  let arrayLiteral;
  for (const statement of source.statements) {
    if (!ts.isVariableStatement(statement)) continue;
    for (const decl of statement.declarationList.declarations) {
      if (
        ts.isIdentifier(decl.name) &&
        decl.name.text === "CUMULUS_COMPONENTS" &&
        decl.initializer &&
        ts.isArrayLiteralExpression(decl.initializer)
      ) {
        arrayLiteral = decl.initializer;
      }
    }
  }
  if (!arrayLiteral) {
    throw new Error(
      `${fileName}: could not find the CUMULUS_COMPONENTS array literal`,
    );
  }

  const entries = [];
  for (const element of arrayLiteral.elements) {
    if (!ts.isIdentifier(element)) {
      throw new Error(
        `${fileName}: CUMULUS_COMPONENTS entries must be plain identifiers (got ${ts.SyntaxKind[element.kind]})`,
      );
    }
    const modulePath = importByName.get(element.text);
    if (!modulePath) {
      throw new Error(
        `${fileName}: CUMULUS_COMPONENTS entry "${element.text}" has no matching import`,
      );
    }
    entries.push({ exportName: element.text, modulePath });
  }
  return entries;
}

/**
 * PURE core: extract the doc-relevant fields of a demo file's CumulusComponent
 * object literal — id, title, blurb, callout?, details?, propsNote?, group, docName,
 * usage[] — from source text. When `exportName` is given, that exported const is required;
 * otherwise the first exported const initialized to an object literal with an
 * `id` property is used (test convenience).
 */
export function extractDemoDoc(sourceText, fileName, exportName) {
  const source = parseSource(sourceText, fileName);

  let objectLiteral;
  for (const statement of source.statements) {
    if (!ts.isVariableStatement(statement)) continue;
    const isExported = statement.modifiers?.some(
      (m) => m.kind === ts.SyntaxKind.ExportKeyword,
    );
    if (!isExported) continue;
    for (const decl of statement.declarationList.declarations) {
      if (!ts.isIdentifier(decl.name)) continue;
      if (
        !decl.initializer ||
        !ts.isObjectLiteralExpression(decl.initializer)
      ) {
        continue;
      }
      if (exportName) {
        if (decl.name.text === exportName) objectLiteral = decl.initializer;
      } else if (propertyInitializer(decl.initializer, "id")) {
        objectLiteral ??= decl.initializer;
      }
    }
  }
  if (!objectLiteral) {
    throw new Error(
      `${fileName}: could not find exported CumulusComponent object literal${exportName ? ` "${exportName}"` : ""}`,
    );
  }

  function requiredString(field) {
    const init = propertyInitializer(objectLiteral, field);
    if (!init) {
      throw new Error(`${fileName}: missing required field "${field}"`);
    }
    return literalString(init, `${fileName} field "${field}"`);
  }

  function optionalString(field) {
    const init = propertyInitializer(objectLiteral, field);
    if (!init) return undefined;
    return literalString(init, `${fileName} field "${field}"`);
  }

  function optionalStringArray(field) {
    const init = propertyInitializer(objectLiteral, field);
    if (!init) return undefined;
    if (!ts.isArrayLiteralExpression(init)) {
      throw new Error(`${fileName}: field "${field}" must be an array literal`);
    }
    if (init.elements.length === 0) {
      throw new Error(`${fileName}: field "${field}" must not be empty`);
    }
    return init.elements.map((element, index) =>
      literalString(element, `${fileName} field "${field}"[${index}]`),
    );
  }

  function documentationString(value, context) {
    const screenOwnershipClaim =
      /\bproduct owner(?:ship)?\b/i.test(value) ||
      /\bscreen-owned\b/i.test(value) ||
      /\b(?:[A-Za-z][A-Za-z0-9]*Screen|screen)\b[^.!?\n]{0,80}\bowns?\b/i.test(
        value,
      );
    if (screenOwnershipClaim) {
      throw new Error(
        `${context}: Cumulus component docs describe roles and contracts, not screen ownership claims`,
      );
    }
    return value;
  }

  const usageInit = propertyInitializer(objectLiteral, "usage");
  if (!usageInit || !ts.isArrayLiteralExpression(usageInit)) {
    throw new Error(`${fileName}: missing or non-array "usage" field`);
  }
  const usage = usageInit.elements.map((element, index) => {
    if (!ts.isObjectLiteralExpression(element)) {
      throw new Error(`${fileName}: usage[${index}] must be an object literal`);
    }
    const codeInit = propertyInitializer(element, "code");
    if (!codeInit) {
      throw new Error(`${fileName}: usage[${index}] is missing "code"`);
    }
    const entry = {
      code: literalString(codeInit, `${fileName} usage[${index}].code`),
    };
    const labelInit = propertyInitializer(element, "label");
    if (labelInit) {
      entry.label = literalString(
        labelInit,
        `${fileName} usage[${index}].label`,
      );
    }
    const noteInit = propertyInitializer(element, "note");
    if (noteInit) {
      const context = `${fileName} usage[${index}].note`;
      entry.note = documentationString(
        literalString(noteInit, context),
        context,
      );
    }
    return entry;
  });

  const blurbContext = `${fileName} field "blurb"`;
  const calloutContext = `${fileName} field "callout"`;
  const detailsContext = `${fileName} field "details"`;
  const propsNoteContext = `${fileName} field "propsNote"`;
  const callout = optionalString("callout");
  const details = optionalStringArray("details");
  const propsNote = optionalString("propsNote");
  if (callout !== undefined && sentenceCount(callout) !== 1) {
    throw new Error(
      `${calloutContext}: info callouts must contain exactly one sentence; move supporting prose to "details"`,
    );
  }
  return {
    id: requiredString("id"),
    title: requiredString("title"),
    blurb: documentationString(requiredString("blurb"), blurbContext),
    callout:
      callout === undefined
        ? undefined
        : documentationString(callout, calloutContext),
    details: details?.map((paragraph) =>
      documentationString(paragraph, detailsContext),
    ),
    propsNote:
      propsNote === undefined
        ? undefined
        : documentationString(propsNote, propsNoteContext),
    group: requiredString("group"),
    docName: requiredString("docName"),
    usage,
  };
}

/**
 * Render text for a markdown table cell: collapse whitespace runs (JSDoc
 * descriptions wrap across lines) and escape pipes so union types don't break
 * the row.
 */
function tableCell(text) {
  return String(text ?? "")
    .replace(/\s+/g, " ")
    .trim()
    .replace(/\|/g, "\\|");
}

/**
 * Wrap text in a markdown code span, choosing a backtick fence longer than any
 * backtick run inside it (type strings can contain template-literal backticks,
 * e.g. `#${string}`).
 */
function codeSpan(text) {
  const content = String(text ?? "");
  if (content.length === 0) return "";
  const runs = content.match(/`+/g);
  const fence = "`".repeat(
    runs ? Math.max(...runs.map((r) => r.length)) + 1 : 1,
  );
  const pad = content.startsWith("`") || content.endsWith("`") ? " " : "";
  return `${fence}${pad}${content}${pad}${fence}`;
}

/**
 * Render a prop's type cell. When docgen captured string-literal union
 * members behind a named alias (e.g. `ButtonSize` = "sm" | "md" | "lg"), the
 * allowed values are spelled out next to the alias — the alias name alone
 * tells a reader nothing about what to pass. A tsType that already spells the
 * literals is shown as-is.
 */
function typeCell(prop) {
  const alias = codeSpan(tableCell(prop.tsType));
  if (!prop.unionMembers || prop.unionMembers.length === 0) return alias;
  const literals = prop.unionMembers.map((m) => `"${m}"`).join(" | ");
  if (prop.tsType.includes('"')) return alias;
  return `${alias} = ${codeSpan(tableCell(literals))}`;
}

/** First sentence of a blurb, for the one-line index summary. */
export function firstSentence(text) {
  const collapsed = String(text ?? "")
    .replace(/\s+/g, " ")
    .trim();
  const match = collapsed.match(/^.*?[.!?](?=\s|$)/);
  return match ? match[0] : collapsed;
}

/** Count human-readable sentences using the platform's locale-aware segmenter. */
export function sentenceCount(text) {
  // Segmenter treats a capitalized word after these abbreviations as a new
  // sentence. Mask their periods only in the temporary analysis string.
  const normalized = String(text ?? "").replace(
    /\b(?:e\.g|i\.e|vs|Dr|Mr|Mrs|Ms|Prof|Sr|Jr|Fig)\./gi,
    (abbreviation) => abbreviation.replaceAll(".", "_"),
  );
  const segmenter = new Intl.Segmenter("en", { granularity: "sentence" });
  return [...segmenter.segment(normalized)].filter(
    ({ segment }) => segment.trim().length > 0,
  ).length;
}

