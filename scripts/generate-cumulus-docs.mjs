// Generates the agent-facing markdown reference for the Cumulus design system.
//
//   node scripts/generate-cumulus-docs.mjs   # also: npm run cumulus-docs
//
// Writes one markdown file per documented Cumulus component to
// .llms/skills/cumulus/components/<id>.md, a design-token reference to
// .llms/skills/cumulus/tokens.md, and splices a component index table into
// .llms/skills/cumulus/SKILL.md between the GENERATED COMPONENT INDEX markers.
// All outputs are projections of the same sources the /cumulus doc site
// renders, so the skill reference can never drift from the site:
//
//   - src/cumulus/docs/registry.ts          canonical component list + order
//   - src/cumulus/docs/demos/<id>.tsx       authored prose: blurb, callout,
//                                           details, usage
//   - src/cumulus/metadata/cumulus-metadata.json  docgen props (run cumulus-metadata
//                                             first; regenerate-assets does)
//   - src/cumulus/primitives/cumulus-tokens.css   public design-token vocabulary
//
// The demo prose (id, title, blurb, callout, details, group, docName, usage snippets)
// is extracted statically from the demo files' object literals with the
// TypeScript AST — the modules are never executed, so their JSX/CSS imports
// don't matter. Doc-relevant fields must therefore be plain string literals or
// substitution-free template literals; a `${...}` substitution in one is a
// hard error telling the author to keep doc strings literal.
//
// The generator owns the components/ output directory: it deletes any .md file
// it did not just write, so a renamed or unregistered component cannot leave a
// stale reference behind that reads as authoritative.
//
// The output is committed (regenerated by `npm run regenerate-assets`) — rerun
// after adding or editing a Cumulus component or its demo entry.

