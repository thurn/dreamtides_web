// Generates the agent-facing markdown reference for the Tango design system.
//
//   node scripts/generate-tango-docs.mjs   # also: npm run tango-docs
//
// Writes one markdown file per documented Tango component to
// .llms/skills/tango/components/<id>.md, and splices a component index table
// into .llms/skills/tango/SKILL.md between the GENERATED COMPONENT INDEX
// markers. Both outputs are projections of the same sources the /tango doc
// site renders, so the skill reference can never drift from the site:
//
//   - src/tango/docs/registry.ts          canonical component list + order
//   - src/tango/docs/demos/<id>.tsx       authored prose: blurb, callout, usage
//   - src/tango/metadata/tango-metadata.json  docgen props (run tango-metadata
//                                             first; regenerate-assets does)
//
// The demo prose (id, title, blurb, callout, group, docName, usage snippets)
// is extracted statically from the demo files' object literals with the
// TypeScript AST — the modules are never executed, so their JSX/CSS imports
// don't matter. Doc-relevant fields must therefore be plain string literals or
// substitution-free template literals; a `${...}` substitution in one is a
// hard error telling the author to keep doc strings literal.
//
// The generator owns the components/ output directory: it deletes any .md file
// it did not just write, so a renamed or unregistered component cannot leave a
// stale reference behind that reads as authoritative.
//
// The output is committed (regenerated by `npm run regenerate-assets`) — rerun
// after adding or editing a Tango component or its demo entry.

import {
  readdirSync,
  readFileSync,
  writeFileSync,
  mkdirSync,
  unlinkSync,
} from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join, relative, resolve } from "node:path";
import ts from "typescript";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const REGISTRY_PATH = resolve(ROOT, "src/tango/docs/registry.ts");
const DEMOS_DIR = resolve(ROOT, "src/tango/docs/demos");
const METADATA_PATH = resolve(ROOT, "src/tango/metadata/tango-metadata.json");
const SKILL_DIR = resolve(ROOT, ".llms/skills/tango");
const COMPONENTS_OUT_DIR = join(SKILL_DIR, "components");
const SKILL_PATH = join(SKILL_DIR, "SKILL.md");

export const INDEX_BEGIN_MARKER =
  "<!-- BEGIN GENERATED COMPONENT INDEX (npm run tango-docs) -->";
export const INDEX_END_MARKER = "<!-- END GENERATED COMPONENT INDEX -->";

/** Parse a source text into a TS AST without touching the filesystem. */
function parseSource(sourceText, fileName) {
  return ts.createSourceFile(
    fileName,
    sourceText,
    ts.ScriptTarget.Latest,
    /* setParentNodes */ true,
    fileName.endsWith(".tsx") ? ts.ScriptKind.TSX : ts.ScriptKind.TS,
  );
}

/**
 * Extract the literal string value of an AST node, or throw. Accepts a plain
 * string literal and a substitution-free template literal — the two forms the
 * demo files use for doc prose. Anything else (a template with `${...}`, an
 * identifier, a concatenation) is rejected so doc fields stay statically
 * extractable.
 */
function literalString(node, context) {
  if (ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node)) {
    return node.text;
  }
  if (ts.isTemplateExpression(node)) {
    throw new Error(
      `${context}: template literal uses \${...} substitution; doc fields must be plain literals so the tango-docs generator can extract them statically`,
    );
  }
  throw new Error(
    `${context}: expected a string literal (got ${ts.SyntaxKind[node.kind]})`,
  );
}

/** Find an object literal's property initializer by name, or undefined. */
function propertyInitializer(objectLiteral, name) {
  for (const prop of objectLiteral.properties) {
    if (
      ts.isPropertyAssignment(prop) &&
      ts.isIdentifier(prop.name) &&
      prop.name.text === name
    ) {
      return prop.initializer;
    }
  }
  return undefined;
}

/**
 * PURE core: parse registry.ts source text into the ordered component list —
 * `[{ exportName, modulePath }]` in TANGO_COMPONENTS order, where modulePath
 * is the import specifier (e.g. "./demos/pressable"). Order is the canonical
 * catalog order the doc site's table of contents renders.
 */
export function extractRegistryOrder(sourceText, fileName = "registry.ts") {
  const source = parseSource(sourceText, fileName);

  // Map each imported identifier to its module specifier.
  const importByName = new Map();
  for (const statement of source.statements) {
    if (!ts.isImportDeclaration(statement)) continue;
    const clause = statement.importClause;
    if (!clause?.namedBindings || !ts.isNamedImports(clause.namedBindings)) {
      continue;
    }
    const specifier = statement.moduleSpecifier;
    if (!ts.isStringLiteral(specifier)) continue;
    for (const element of clause.namedBindings.elements) {
      importByName.set(element.name.text, specifier.text);
    }
  }

  // Find the TANGO_COMPONENTS array literal and read its identifiers in order.
  let arrayLiteral;
  for (const statement of source.statements) {
    if (!ts.isVariableStatement(statement)) continue;
    for (const decl of statement.declarationList.declarations) {
      if (
        ts.isIdentifier(decl.name) &&
        decl.name.text === "TANGO_COMPONENTS" &&
        decl.initializer &&
        ts.isArrayLiteralExpression(decl.initializer)
      ) {
        arrayLiteral = decl.initializer;
      }
    }
  }
  if (!arrayLiteral) {
    throw new Error(
      `${fileName}: could not find the TANGO_COMPONENTS array literal`,
    );
  }

  const entries = [];
  for (const element of arrayLiteral.elements) {
    if (!ts.isIdentifier(element)) {
      throw new Error(
        `${fileName}: TANGO_COMPONENTS entries must be plain identifiers (got ${ts.SyntaxKind[element.kind]})`,
      );
    }
    const modulePath = importByName.get(element.text);
    if (!modulePath) {
      throw new Error(
        `${fileName}: TANGO_COMPONENTS entry "${element.text}" has no matching import`,
      );
    }
    entries.push({ exportName: element.text, modulePath });
  }
  return entries;
}

/**
 * PURE core: extract the doc-relevant fields of a demo file's TangoComponent
 * object literal — id, title, blurb, callout?, group, docName, usage[] — from
 * source text. When `exportName` is given, that exported const is required;
 * otherwise the first exported const initialized to an object literal with an
 * `id` property is used (test convenience).
 */
export function extractDemoDoc(sourceText, fileName, exportName) {
  const source = parseSource(sourceText, fileName);

  let objectLiteral;
  for (const statement of source.statements) {
    if (!ts.isVariableStatement(statement)) continue;
    const isExported = statement.modifiers?.some(
      (m) => m.kind === ts.SyntaxKind.ExportKeyword,
    );
    if (!isExported) continue;
    for (const decl of statement.declarationList.declarations) {
      if (!ts.isIdentifier(decl.name)) continue;
      if (!decl.initializer || !ts.isObjectLiteralExpression(decl.initializer)) {
        continue;
      }
      if (exportName) {
        if (decl.name.text === exportName) objectLiteral = decl.initializer;
      } else if (propertyInitializer(decl.initializer, "id")) {
        objectLiteral ??= decl.initializer;
      }
    }
  }
  if (!objectLiteral) {
    throw new Error(
      `${fileName}: could not find exported TangoComponent object literal${exportName ? ` "${exportName}"` : ""}`,
    );
  }

  function requiredString(field) {
    const init = propertyInitializer(objectLiteral, field);
    if (!init) {
      throw new Error(`${fileName}: missing required field "${field}"`);
    }
    return literalString(init, `${fileName} field "${field}"`);
  }

  function optionalString(field) {
    const init = propertyInitializer(objectLiteral, field);
    if (!init) return undefined;
    return literalString(init, `${fileName} field "${field}"`);
  }

  const usageInit = propertyInitializer(objectLiteral, "usage");
  if (!usageInit || !ts.isArrayLiteralExpression(usageInit)) {
    throw new Error(`${fileName}: missing or non-array "usage" field`);
  }
  const usage = usageInit.elements.map((element, index) => {
    if (!ts.isObjectLiteralExpression(element)) {
      throw new Error(
        `${fileName}: usage[${index}] must be an object literal`,
      );
    }
    const codeInit = propertyInitializer(element, "code");
    if (!codeInit) {
      throw new Error(`${fileName}: usage[${index}] is missing "code"`);
    }
    const entry = {
      code: literalString(codeInit, `${fileName} usage[${index}].code`),
    };
    const labelInit = propertyInitializer(element, "label");
    if (labelInit) {
      entry.label = literalString(
        labelInit,
        `${fileName} usage[${index}].label`,
      );
    }
    const noteInit = propertyInitializer(element, "note");
    if (noteInit) {
      entry.note = literalString(noteInit, `${fileName} usage[${index}].note`);
    }
    return entry;
  });

  return {
    id: requiredString("id"),
    title: requiredString("title"),
    blurb: requiredString("blurb"),
    callout: optionalString("callout"),
    group: requiredString("group"),
    docName: requiredString("docName"),
    usage,
  };
}

/**
 * Render text for a markdown table cell: collapse whitespace runs (JSDoc
 * descriptions wrap across lines) and escape pipes so union types don't break
 * the row.
 */
function tableCell(text) {
  return String(text ?? "")
    .replace(/\s+/g, " ")
    .trim()
    .replace(/\|/g, "\\|");
}

/**
 * Wrap text in a markdown code span, choosing a backtick fence longer than any
 * backtick run inside it (type strings can contain template-literal backticks,
 * e.g. `#${string}`).
 */
function codeSpan(text) {
  const content = String(text ?? "");
  if (content.length === 0) return "";
  const runs = content.match(/`+/g);
  const fence = "`".repeat(runs ? Math.max(...runs.map((r) => r.length)) + 1 : 1);
  const pad = content.startsWith("`") || content.endsWith("`") ? " " : "";
  return `${fence}${pad}${content}${pad}${fence}`;
}

/**
 * Render a prop's type cell. When docgen captured string-literal union
 * members behind a named alias (e.g. `ButtonSize` = "sm" | "md" | "lg"), the
 * allowed values are spelled out next to the alias — the alias name alone
 * tells a reader nothing about what to pass. A tsType that already spells the
 * literals is shown as-is.
 */
function typeCell(prop) {
  const alias = codeSpan(tableCell(prop.tsType));
  if (!prop.unionMembers || prop.unionMembers.length === 0) return alias;
  const literals = prop.unionMembers.map((m) => `"${m}"`).join(" | ");
  if (prop.tsType.includes('"')) return alias;
  return `${alias} = ${codeSpan(tableCell(literals))}`;
}

/** First sentence of a blurb, for the one-line index summary. */
export function firstSentence(text) {
  const collapsed = String(text ?? "").replace(/\s+/g, " ").trim();
  const match = collapsed.match(/^.*?[.!?](?=\s|$)/);
  return match ? match[0] : collapsed;
}

const GENERATED_HEADER = (id) =>
  `<!-- GENERATED by scripts/generate-tango-docs.mjs — do not edit by hand.
     Sources: the component's prop JSDoc (via tango-metadata.json) and its demo
     entry in src/tango/docs/demos/${id}.tsx. Regenerate: npm run tango-docs -->`;

/**
 * PURE core: render one component's markdown reference from its demo doc and
 * docgen PropMeta[] (the tango-metadata.json entry under doc.docName).
 */
export function renderComponentMarkdown(doc, props) {
  const lines = [];
  lines.push(GENERATED_HEADER(doc.id));
  lines.push("");
  lines.push(`# ${doc.title}`);
  lines.push("");
  lines.push(
    `${doc.group} · Live demo & interactive props: \`/tango#/${doc.id}\``,
  );
  lines.push("");
  lines.push(doc.blurb);
  if (doc.callout) {
    lines.push("");
    lines.push(`> **Guidance:** ${doc.callout}`);
  }

  lines.push("");
  lines.push("## Props");
  lines.push("");
  if (!props || props.length === 0) {
    lines.push("This component takes no props.");
  } else {
    lines.push("| Prop | Type | Required | Default | Description |");
    lines.push("| --- | --- | --- | --- | --- |");
    for (const prop of props) {
      lines.push(
        `| ${codeSpan(prop.name)} | ${typeCell(prop)} | ${prop.required ? "yes" : "no"} | ${prop.defaultValue !== null && prop.defaultValue !== undefined ? codeSpan(tableCell(prop.defaultValue)) : "—"} | ${tableCell(prop.description)} |`,
      );
    }
    for (const prop of props) {
      if (!prop.nested || !prop.nested.fields?.length) continue;
      lines.push("");
      lines.push(
        `### ${codeSpan(prop.name)}: the ${codeSpan(prop.nested.name)} model`,
      );
      lines.push("");
      lines.push("| Field | Type | Optional | Description |");
      lines.push("| --- | --- | --- | --- |");
      for (const field of prop.nested.fields) {
        lines.push(
          `| ${codeSpan(field.name)} | ${codeSpan(tableCell(field.tsType))} | ${field.optional ? "yes" : "no"} | ${tableCell(field.description)} |`,
        );
      }
    }
  }

  if (doc.usage.length > 0) {
    lines.push("");
    lines.push("## Usage");
    for (const [index, snippet] of doc.usage.entries()) {
      lines.push("");
      if (snippet.label) {
        lines.push(`### ${snippet.label}`);
        lines.push("");
      } else if (doc.usage.length > 1) {
        lines.push(`### Variant ${index + 1}`);
        lines.push("");
      }
      if (snippet.note) {
        lines.push(snippet.note);
        lines.push("");
      }
      lines.push("```tsx");
      lines.push(snippet.code);
      lines.push("```");
    }
  }

  lines.push("");
  return lines.join("\n");
}

/**
 * PURE core: render the component index table (registry order, grouped by
 * first appearance of each group) that gets spliced into SKILL.md.
 */
export function renderIndexSection(docs) {
  const lines = [];
  lines.push("| Component | Group | Reference | What it is |");
  lines.push("| --- | --- | --- | --- |");
  for (const doc of docs) {
    lines.push(
      `| ${doc.title} | ${doc.group} | [components/${doc.id}.md](components/${doc.id}.md) | ${tableCell(firstSentence(doc.blurb))} |`,
    );
  }
  return lines.join("\n");
}

/**
 * PURE core: replace the generated index section of SKILL.md (the text between
 * the BEGIN/END markers) with freshly rendered content. Throws when a marker
 * is missing so a hand-edit that drops one fails loudly instead of silently
 * skipping the update.
 */
export function spliceGeneratedIndex(skillText, indexMarkdown) {
  const begin = skillText.indexOf(INDEX_BEGIN_MARKER);
  const end = skillText.indexOf(INDEX_END_MARKER);
  if (begin === -1 || end === -1 || end < begin) {
    throw new Error(
      `SKILL.md is missing the generated-index markers (${INDEX_BEGIN_MARKER} / ${INDEX_END_MARKER})`,
    );
  }
  const before = skillText.slice(0, begin + INDEX_BEGIN_MARKER.length);
  const after = skillText.slice(end);
  return `${before}\n${indexMarkdown}\n${after}`;
}

function main() {
  const registryEntries = extractRegistryOrder(
    readFileSync(REGISTRY_PATH, "utf8"),
    relative(ROOT, REGISTRY_PATH),
  );
  const metadata = JSON.parse(readFileSync(METADATA_PATH, "utf8"));

  const docs = [];
  for (const entry of registryEntries) {
    // Import specifiers are relative to the registry file, without extension.
    const demoPath = `${resolve(dirname(REGISTRY_PATH), entry.modulePath)}.tsx`;
    const doc = extractDemoDoc(
      readFileSync(demoPath, "utf8"),
      relative(ROOT, demoPath),
      entry.exportName,
    );
    if (!(doc.docName in metadata)) {
      throw new Error(
        `${relative(ROOT, demoPath)}: docName "${doc.docName}" has no entry in ${relative(ROOT, METADATA_PATH)} — run npm run tango-metadata first`,
      );
    }
    docs.push(doc);
  }

  const ids = new Set(docs.map((doc) => doc.id));
  if (ids.size !== docs.length) {
    throw new Error("duplicate component ids in the registry");
  }

  // Write one reference file per component, then sweep stale ones: any .md in
  // the output directory this run did not produce belongs to a renamed or
  // unregistered component and must not survive as authoritative-looking docs.
  mkdirSync(COMPONENTS_OUT_DIR, { recursive: true });
  const writtenFiles = new Set();
  for (const doc of docs) {
    const fileName = `${doc.id}.md`;
    writeFileSync(
      join(COMPONENTS_OUT_DIR, fileName),
      renderComponentMarkdown(doc, metadata[doc.docName]),
    );
    writtenFiles.add(fileName);
  }
  let sweptCount = 0;
  for (const existing of readdirSync(COMPONENTS_OUT_DIR)) {
    if (existing.endsWith(".md") && !writtenFiles.has(existing)) {
      unlinkSync(join(COMPONENTS_OUT_DIR, existing));
      sweptCount += 1;
    }
  }

  const skillText = readFileSync(SKILL_PATH, "utf8");
  writeFileSync(
    SKILL_PATH,
    spliceGeneratedIndex(skillText, renderIndexSection(docs)),
  );

  console.log(
    `Wrote ${docs.length} component reference${docs.length === 1 ? "" : "s"} to ${relative(ROOT, COMPONENTS_OUT_DIR)}${sweptCount > 0 ? ` (swept ${sweptCount} stale)` : ""}`,
  );
  console.log(`Updated component index in ${relative(ROOT, SKILL_PATH)}`);
}

const invokedPath = process.argv[1] ? resolve(process.argv[1]) : "";
if (invokedPath === fileURLToPath(import.meta.url)) main();
