import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = process.cwd();
const bundlePath = resolve(root, "src/generated/localization/en-US.trox.json");
const outputPath = resolve(
  root,
  "src/runtime/localization/runtime-templates.generated.ts",
);
const bundle = JSON.parse(readFileSync(bundlePath, "utf8"));
const cardData = JSON.parse(
  readFileSync(resolve(root, "public/card-data.json"), "utf8"),
);
const dreamGuideData = JSON.parse(
  readFileSync(resolve(root, "public/dream-guides-data.json"), "utf8"),
);
const dreamsignData = JSON.parse(
  readFileSync(resolve(root, "public/dreamsign-data.json"), "utf8"),
);
const cardSubtypes = [
  ...new Set(
    cardData
      .map((card) => card.subtype)
      .filter((subtype) => subtype !== "" && subtype !== "*"),
  ),
].sort((left, right) => left.localeCompare(right));

const guideDialogue = dreamGuideData.guides.flatMap((guide) =>
  Object.values(guide.dialogue).flat(),
);
const templates = [
  ...new Set(
    [
      ...Object.values(bundle.entries)
        .map((entry) => entry.identity?.pattern)
        .filter(
          (pattern) =>
            pattern?.kind === "text" && pattern.text.includes("{{"),
        )
        .map((pattern) =>
          pattern.text.replace(/\{\{([^{}]+)\}\}/gu, "{$1}"),
        ),
      ...guideDialogue.filter((line) => line.includes("{")),
    ],
  ),
].sort((left, right) => left.localeCompare(right));
const staticGuideDialogue = [
  ...new Set(guideDialogue.filter((line) => !line.includes("{"))),
].sort((left, right) => left.localeCompare(right));
const dreamsignImageAlts = [
  ...new Set(
    dreamsignData
      .map((dreamsign) => dreamsign.imageAlt)
      .filter((imageAlt) => imageAlt !== undefined && imageAlt !== ""),
  ),
].sort((left, right) => left.localeCompare(right));

function argumentName(sourceName) {
  const normalized =
    sourceName === "name"
      ? "affiliation_name"
      : /^[0-9]+$/u.test(sourceName)
        ? `value_${sourceName}`
        : sourceName
            .replace(/([a-z0-9])([A-Z])/gu, "$1_$2")
            .replaceAll("-", "_")
            .toLowerCase();
  if (!/^[a-z][a-z0-9]*(?:_[a-z0-9]+)*$/u.test(normalized)) {
    throw new Error(
      `Cannot normalize runtime-template argument ${JSON.stringify(sourceName)}.`,
    );
  }
  return normalized;
}

function templateCase(template) {
  const sourceNames = [...template.matchAll(/\{([^{}]+)\}/gu)].map(
    (match) => match[1],
  );
  const uniqueSourceNames = [...new Set(sourceNames)];
  const normalizedNames = uniqueSourceNames.map(argumentName);
  if (new Set(normalizedNames).size !== normalizedNames.length) {
    throw new Error(
      `Runtime-template arguments collide after normalization: ${template}`,
    );
  }
  const pattern = template.replace(
    /\{([^{}]+)\}/gu,
    (_match, name) => `{${argumentName(name)}}`,
  );
  const inputs = uniqueSourceNames
    .map(
      (name) =>
        `          ${argumentName(name)}: runtimeTemplateArgument(values, ${JSON.stringify(name)}),`,
    )
    .join("\n");
  return `    case ${JSON.stringify(template)}:\n      return txa(\n        ${JSON.stringify(pattern)},\n        {\n${inputs}\n        },\n        "[game-data] Template whose runtime arguments are semantic values supplied by the presentation adapter.",\n      );`;
}

const source = `// Generated by scripts/generate-localized-runtime-templates.mjs. Do not edit.
//
// Canonical RON Tx values are static by contract. This module re-authors the
// finite compatibility templates as statically extractable Trox messages so
// runtime adapters can supply arguments without returning plain strings.

import {
  LocalizedString,
  opaque,
  tx,
  txa,
  type ArgumentInput,
} from "@trox/runtime";

export type RuntimeTemplateValue = number | boolean | LocalizedString;

// This statically enumerable vocabulary backs subtype names stored as raw
// structural values in the compatibility card catalog.
export function localizedCardSubtype(sourceText: string): LocalizedString | null {
  switch (sourceText) {
${cardSubtypes.map((subtype) => `    case ${JSON.stringify(subtype)}:\n      return tx(${JSON.stringify(subtype)}, "[card] Character subtype name.");`).join("\n")}
    default:
      return null;
  }
}

// Dream Guide dialogue is nested compatibility data. Enumerating it here keeps
// every authored line statically extractable even when a line is selected at runtime.
export function localizedGuideDialogue(sourceText: string): LocalizedString | null {
  switch (sourceText) {
${staticGuideDialogue.map((line) => `    case ${JSON.stringify(line)}:\n      return tx(${JSON.stringify(line)}, "[dream-guide] Dream Guide dialogue.");`).join("\n")}
    default:
      return null;
  }
}

// Dreamsign image descriptions are accessibility copy carried by compatibility
// JSON, so enumerate the finite vocabulary as statically extractable messages.
export function localizedDreamsignImageAlt(sourceText: string): LocalizedString | null {
  switch (sourceText) {
${dreamsignImageAlts.map((line) => `    case ${JSON.stringify(line)}:\n      return tx(${JSON.stringify(line)}, "[accessibility] [dreamsign] Dreamsign image description.");`).join("\n")}
    default:
      return null;
  }
}

function runtimeTemplateArgument(
  values: Readonly<Record<string, RuntimeTemplateValue>>,
  name: string,
): ArgumentInput {
  const value = values[name];
  if (value === undefined) throw new Error(\`missing value for {\${name}}\`);
  return value instanceof LocalizedString ? opaque(value) : value;
}

export function localizedRuntimeTemplate(
  sourceText: string,
  values: Readonly<Record<string, RuntimeTemplateValue>>,
): LocalizedString | null {
  switch (sourceText) {
${templates.map(templateCase).join("\n")}
    default:
      return null;
  }
}
`;

writeFileSync(outputPath, source);
console.log(
  `Wrote ${templates.length} localized runtime templates, ${cardSubtypes.length} card subtypes, ${staticGuideDialogue.length} Dream Guide lines, and ${dreamsignImageAlts.length} Dreamsign image descriptions to ${outputPath}`,
);
