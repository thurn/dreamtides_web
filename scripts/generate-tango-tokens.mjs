// Generates the typed mirror of the Tango design tokens.
//
//   node scripts/generate-tango-tokens.mjs   # writes src/tango/primitives/tokens.ts
//                                             # also: npm run tango-tokens
//
// src/tango/primitives/tango-tokens.css is the source of truth: every design
// token is a CSS custom property declared there. This script parses that
// file with parseCssTokens (scripts/lib/tango-css-tokens.mjs) and writes a
// typed tokens.ts that downstream Tango TS/demo code imports instead of
// stringly-typed `var(--...)` literals.
//
// tango-tokens.css declares a handful of names twice (e.g. --text-faint is
// first pinned to a placeholder and later re-pointed at the real semantic
// alias). The browser resolves a repeated custom-property declaration
// last-wins, per the CSS cascade, so this generator dedupes the same way:
// later declarations overwrite the value of an earlier one with the same
// name, while the name keeps the output position of its *first*
// occurrence (matching plain `Map.set` semantics, which never reorders an
// existing key).
//
// The generated file is committed (it's under src/, so `tsc` typechecks it
// on every run) and is part of `npm run regenerate-assets` — rerun this
// script after editing tango-tokens.css so tokens.ts never drifts from it.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join, relative, resolve } from "node:path";
import { parseCssTokens } from "./lib/tango-css-tokens.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const CSS_PATH = join(ROOT, "src/tango/primitives/tango-tokens.css");
const OUT_PATH = join(ROOT, "src/tango/primitives/tokens.ts");

const HEADER = `// GENERATED by scripts/generate-tango-tokens.mjs from tango-tokens.css. Do
// not edit by hand — rerun \`npm run tango-tokens\` (or
// \`npm run regenerate-assets\`) after changing tango-tokens.css.
//
// Typed mirror of the CSS custom properties declared in
// src/tango/primitives/tango-tokens.css, which remains the source of truth
// for every token's value. Each entry carries the \`var(--name)\` reference
// string, for use in inline styles or CSS-in-JS, the token's raw declared
// value (which may itself be another \`var(...)\` reference, matching how the
// CSS resolves it), and — where the source CSS annotates the declaration with
// a trailing \`/* @kind ... */\` marker — that marker's value, read by the
// Primitives doc section to group tokens for display. A name declared more
// than once in the source CSS is deduped last-wins, mirroring the CSS
// cascade (the \`kind\` of the last declaration wins too).`;

/**
 * Reduce a parsed token list (which may contain repeated names, in source
 * order) to one entry per name, keeping the *last* declaration's value and
 * kind — matching how the CSS cascade resolves a repeated custom property.
 *
 * Uses `Map#set`'s documented behavior of never moving an already-present
 * key, so the returned order is "first occurrence position, last-declared
 * value" without any extra bookkeeping.
 *
 * @param {Array<{ name: string, value: string, kind?: string }>} tokens
 * @returns {Map<string, { value: string, kind?: string }>}
 */
export function dedupeLastWins(tokens) {
  const byName = new Map();
  for (const { name, value, kind } of tokens) {
    byName.set(name, { value, kind });
  }
  return byName;
}

/**
 * Pure transform from parsed CSS tokens to the generated tokens.ts source
 * text. Exported so tests can check the transform directly against small
 * inline fixtures, without touching the filesystem.
 *
 * @param {Array<{ name: string, value: string, kind?: string }>} tokens
 * @returns {string}
 */
export function buildTokensSource(tokens) {
  const byName = dedupeLastWins(tokens);

  const entries = [...byName.entries()].map(([name, { value, kind }]) => {
    const key = JSON.stringify(`--${name}`);
    const varRef = JSON.stringify(`var(--${name})`);
    const rawValue = JSON.stringify(value);
    const kindField = kind !== undefined ? `, kind: ${JSON.stringify(kind)}` : "";
    return `  ${key}: { var: ${varRef}, value: ${rawValue}${kindField} },`;
  });

  return `${HEADER}

export const TOKENS = {
${entries.join("\n")}
} as const;

export type TokenName = keyof typeof TOKENS;

/** Returns the \`var(--name)\` reference string for a token. */
export function token(name: TokenName): string {
  return TOKENS[name].var;
}
`;
}

function main() {
  const css = readFileSync(CSS_PATH, "utf8");
  const tokens = parseCssTokens(css);
  const source = buildTokensSource(tokens);
  writeFileSync(OUT_PATH, source);

  const uniqueCount = dedupeLastWins(tokens).size;
  const duplicateCount = tokens.length - uniqueCount;
  console.log(`Wrote ${relative(ROOT, OUT_PATH)}`);
  console.log(
    `Tokens: ${uniqueCount} unique (${duplicateCount} duplicate declaration${duplicateCount === 1 ? "" : "s"} deduped last-wins)`,
  );
}

const invokedPath = process.argv[1] ? resolve(process.argv[1]) : "";
if (invokedPath === fileURLToPath(import.meta.url)) main();
