import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { FluentParser, Message, Visitor } from "@fluent/syntax";
import { format } from "prettier";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const SOURCE_PATH = resolve(ROOT, "data/tabula/strings.ftl");
export const OUTPUT_PATH = resolve(ROOT, "src/data/localization-messages.ts");

class VariableCollector extends Visitor {
  variables = new Set();

  visitVariableReference(node) {
    this.variables.add(node.id.name);
  }
}

export function parseMessageContracts(source) {
  const resource = new FluentParser({ withSpans: false }).parse(source);
  const junk = resource.body.filter((entry) => entry.type === "Junk");
  if (junk.length > 0) {
    const diagnostics = junk
      .flatMap((entry) => entry.annotations)
      .map((annotation) => annotation.message)
      .join("; ");
    throw new Error(`Unable to generate localization types: ${diagnostics}`);
  }

  const seen = new Set();
  return resource.body
    .filter((entry) => entry instanceof Message)
    .map((message) => {
      const id = message.id.name;
      if (seen.has(id)) {
        throw new Error(`Duplicate Fluent message ID: ${id}`);
      }
      seen.add(id);

      const collector = new VariableCollector();
      collector.visit(message);
      return {
        id,
        variables: [...collector.variables].sort(),
      };
    });
}

export function buildLocalizationTypesSource(contracts) {
  const rows = contracts.map(({ id, variables }) => {
    const value =
      variables.length === 0
        ? "never"
        : `{ ${variables
            .map(
              (variable) =>
                `readonly ${JSON.stringify(variable)}: FluentVariable`,
            )
            .join("; ")} }`;
    return `  readonly ${JSON.stringify(id)}: ${value};`;
  });

  return `// Generated by scripts/generate-localization-types.mjs. Do not edit.
import type { FluentVariable } from "@fluent/bundle";

export const FLUENT_MESSAGE_IDS = [
${contracts.map(({ id }) => `  ${JSON.stringify(id)},`).join("\n")}
] as const;

export interface FluentMessageArgumentsById {
${rows.join("\n")}
}

export type FluentMessageId = (typeof FLUENT_MESSAGE_IDS)[number];

/** Arguments accepted by a message. Messages that need variables require them. */
export type FluentMessageArguments<Id extends FluentMessageId> =
  Id extends FluentMessageId
    ? FluentMessageArgumentsById[Id] extends never
      ? [variables?: Readonly<Record<string, FluentVariable>>]
      : [variables: FluentMessageArgumentsById[Id]]
    : never;
`;
}

export async function generateLocalizationTypes() {
  const source = readFileSync(SOURCE_PATH, "utf8");
  return format(buildLocalizationTypesSource(parseMessageContracts(source)), {
    parser: "typescript",
  });
}

if (
  process.argv[1] !== undefined &&
  pathToFileURL(resolve(process.argv[1])).href === import.meta.url
) {
  writeFileSync(OUTPUT_PATH, await generateLocalizationTypes());
  process.stdout.write(`Generated ${OUTPUT_PATH}\n`);
}
